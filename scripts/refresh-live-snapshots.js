import fs from "node:fs";
import path from "node:path";

import { fetchLastFmPayload } from "../functions/lib/lastfm.js";
import { fetchSteamRecentActivityPayload } from "../functions/lib/steam.js";

const rootDir = path.resolve(import.meta.dirname, "..");
const josieHtmlPath = path.join(rootDir, "site", "josie.html");
const steamSnapshotPath = path.join(rootDir, "site", "assets", "steam-recent-activity-snapshot.json");
const lastFmSnapshotPath = path.join(rootDir, "functions", "lib", "lastfm-snapshot.js");

function loadDotEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const source = fs.readFileSync(filePath, "utf8");
  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }
    const separatorIndex = line.indexOf("=");
    if (separatorIndex <= 0) {
      continue;
    }
    const key = line.slice(0, separatorIndex).trim();
    let value = line.slice(separatorIndex + 1).trim();
    if (!key || Object.prototype.hasOwnProperty.call(process.env, key)) {
      continue;
    }
    if (
      (value.startsWith("\"") && value.endsWith("\"")) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

function resolveTargets(argv) {
  const targets = new Set();
  for (const arg of argv) {
    const normalized = String(arg || "").trim().toLowerCase().replace(/^--/, "");
    if (!normalized || normalized === "all") {
      targets.add("steam");
      targets.add("lastfm");
      continue;
    }
    if (normalized === "steam" || normalized === "lastfm") {
      targets.add(normalized);
    }
  }
  if (!targets.size) {
    targets.add("steam");
    targets.add("lastfm");
  }
  return targets;
}

function wasTargetExplicit(argv, target) {
  return argv.some((arg) => String(arg || "").trim().toLowerCase().replace(/^--/, "") === target);
}

function isUsableLastFmApiKey(value) {
  const apiKey = String(value || "").trim();
  return Boolean(apiKey && !/^(replace-me|your_|test-key$)/i.test(apiKey));
}

function writeJsonFile(filePath, payload) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(payload, null, 2)}\n`, "utf8");
}

function writeLastFmSnapshotModule(filePath, payload) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const source = [
    "// Generated by npm run refresh:snapshots. Do not edit by hand.",
    `export const LASTFM_SNAPSHOT = ${JSON.stringify(payload, null, 2)};`,
    ""
  ].join("\n");
  fs.writeFileSync(filePath, source, "utf8");
}

function rewriteSteamAvatarPreload(filePath, avatarUrl) {
  const safeAvatarUrl = String(avatarUrl || "").trim();
  if (!safeAvatarUrl || !fs.existsSync(filePath)) {
    return false;
  }
  const source = fs.readFileSync(filePath, "utf8");
  const rewritten = source.replace(
    /(<link\b(?=[^>]*\brel=["']preload["'])(?=[^>]*\bas=["']image["'])(?=[^>]*avatars\.(?:fastly|akamai)\.steamstatic\.com)[^>]*\bhref=["'])https:\/\/avatars\.(?:fastly|akamai)\.steamstatic\.com\/[^"']+(["'][^>]*>)/i,
    `$1${safeAvatarUrl}$2`
  );
  if (rewritten === source) {
    return false;
  }
  fs.writeFileSync(filePath, rewritten, "utf8");
  return true;
}

async function refreshSteamSnapshot(nowMs) {
  const profileUrl = String(process.env.STEAM_PROFILE_URL || "").trim();
  const payload = await fetchSteamRecentActivityPayload(nowMs, { profileUrl });
  writeJsonFile(steamSnapshotPath, payload);
  if (rewriteSteamAvatarPreload(josieHtmlPath, payload?.profile?.avatarUrl)) {
    console.log(`Refreshed Steam avatar preload: ${path.relative(rootDir, josieHtmlPath)}`);
  }
  console.log(`Refreshed Steam snapshot: ${path.relative(rootDir, steamSnapshotPath)}`);
}

async function refreshLastFmSnapshot(nowMs, argv) {
  const apiKey = String(process.env.LASTFM_API_KEY || "").trim();
  if (!isUsableLastFmApiKey(apiKey)) {
    const message = "LASTFM_API_KEY is required to refresh the Last.fm snapshot.";
    if (wasTargetExplicit(argv, "lastfm")) {
      throw new Error(message);
    }
    console.warn(`Skipping Last.fm snapshot: ${message}`);
    return;
  }
  const payload = await fetchLastFmPayload(apiKey, nowMs);
  writeLastFmSnapshotModule(lastFmSnapshotPath, payload);
  console.log(`Refreshed Last.fm snapshot: ${path.relative(rootDir, lastFmSnapshotPath)}`);
}

loadDotEnvFile(path.join(rootDir, ".dev.vars"));

const argv = process.argv.slice(2);
const targets = resolveTargets(argv);
const nowMs = Date.now();

if (targets.has("steam")) {
  await refreshSteamSnapshot(nowMs);
}
if (targets.has("lastfm")) {
  await refreshLastFmSnapshot(nowMs, argv);
}
